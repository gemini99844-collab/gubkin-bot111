# Общий словарь расписаний по группам
ALL_SCHEDULES = {
    "БС-26-05": {
        "upper": BS_26_05_UPPER,
        "lower": BS_26_05_LOWER,
        "overrides": BS_26_05_OVERRIDES,
    },
    "ББ-25-02": {
        "upper": BB_25_02_UPPER,
        "lower": BB_25_02_LOWER,
        "overrides": BB_25_02_OVERRIDES,
    }
}

def get_schedule_for_date(group_name: str, target_date: datetime):
    d = target_date.date()
    sched = ALL_SCHEDULES.get(group_name)
    if not sched:
        return []
    if d in sched["overrides"]:
        return sched["overrides"][d]
    if d < date(2026, 10, 12) or d > date(2027, 1, 3):
        return []
    weekday = d.weekday()
    if get_week_type(d) == "верхняя":
        return sched["upper"].get(weekday, [])
    else:
        return sched["lower"].get(weekday, [])

